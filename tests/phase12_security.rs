const CT_OK: &[u8] =
    b"<Types xmlns=\"http://schemas.openxmlformats.org/package/2006/content-types\"/>";

#[test]
fn xml_doctype_is_refused() {
    let xml = b"<?xml version=\"1.0\"?><!DOCTYPE Types [<!ENTITY x \"y\">]><Types/>";
    assert_eq!(
        class(opc::parse_content_types(xml, Limits::STRICT)),
        Some(ErrorClass::InvalidXmlStructure)
    );
}

#[test]
fn xml_nul_and_non_utf8_are_refused() {
    let mut nul = CT_OK.to_vec();
    nul.push(0);
    assert_eq!(
        class(opc::parse_content_types(&nul, Limits::STRICT)),
        Some(ErrorClass::InvalidXmlStructure)
    );
    let bad = b"<Types>\xff\xfe</Types>";
    assert_eq!(
        class(opc::parse_content_types(bad, Limits::STRICT)),
        Some(ErrorClass::InvalidXmlStructure)
    );
}

#[test]
fn xml_utf16_bom_is_refused() {
    let mut bom = vec![0xFF, 0xFE];
    bom.extend_from_slice(b"<\0T\0>\0");
    assert_eq!(
        class(opc::parse_content_types(&bom, Limits::STRICT)),
        Some(ErrorClass::InvalidXmlStructure)
    );
}

#[test]
fn xml_depth_bomb_is_refused_typed() {
    // Deeper than the STRICT max_xml_depth (64).
    let mut xml = String::from("<Types>");
    for _ in 0..200 {
        xml.push_str("<a>");
    }
    for _ in 0..200 {
        xml.push_str("</a>");
    }
    xml.push_str("</Types>");
    let e = opc::parse_content_types(xml.as_bytes(), Limits::STRICT).unwrap_err();
    assert!(
        matches!(
            e.class(),
            ErrorClass::InvalidXmlStructure | ErrorClass::ResourceLimit
        ),
        "depth bomb gave {e}"
    );
    assert_ne!(e.class(), ErrorClass::InternalInvariant);
}

#[test]
fn malformed_xml_is_typed() {
    let e = opc::parse_content_types(b"<Types><Default></Types>", Limits::STRICT).unwrap_err();
    assert_ne!(e.class(), ErrorClass::InternalInvariant);
}

// ---------------------------------------------------------------------------
// Relationship traps (research I §3): external is inert, traversal is rejected.
// ---------------------------------------------------------------------------

#[test]
fn external_relationship_is_inert_and_traversal_target_is_rejected() {
    let external = b"<Relationships xmlns=\"http://schemas.openxmlformats.org/package/2006/relationships\">\
<Relationship Id=\"r1\" Type=\"urn:x\" Target=\"https://evil.example/x\" TargetMode=\"External\"/></Relationships>";
    let rels =
        opc::parse_relationships(external, "/", Limits::STRICT).expect("parse external rels");
    assert_eq!(rels.len(), 1);
    assert!(rels[0].is_external(), "external rel must be inert");
    assert!(rels[0].resolved.is_none());

    // A traversal target is rejected by the part-name grammar.
    assert_eq!(
        class(opc::resolve_part_target(
            "/word/",
            "../../etc/passwd",
            Limits::STRICT
        )),
        Some(ErrorClass::InvalidPackageStructure)
    );
    // ... absolute URLs are classified as external (inert) by `is_absolute_uri`
    // and are never resolved as an internal package part.
    assert!(opc::is_absolute_uri("https://evil.example/x"));
    assert!(!opc::is_absolute_uri("word/document.xml"));
}

// ---------------------------------------------------------------------------
// EPUB reading path: DOCTYPE in XHTML is refused, script is inert data.
// ---------------------------------------------------------------------------

#[test]
fn xhtml_doctype_is_refused() {
    let xhtml = b"<?xml version=\"1.0\"?><!DOCTYPE html [<!ENTITY e \"x\">]>\
<html xmlns=\"http://www.w3.org/1999/xhtml\"><body><p>&e;</p></body></html>";
    assert_eq!(
        class(epub::content::parse_content(xhtml, "/", Limits::STRICT)),
        Some(ErrorClass::InvalidXmlStructure)
    );
}

#[test]
fn scripted_xhtml_is_parsed_as_inert_data() {
    let xhtml = b"<html xmlns=\"http://www.w3.org/1999/xhtml\"><body>\
<script>fetch(\"http://evil.example/\")</script><p>text</p></body></html>";
    let model = epub::content::parse_content(xhtml, "/", Limits::STRICT).expect("parse");
    assert!(
        model.scripted,
        "script presence must be recorded, not executed"
    );
    assert!(model.text().contains("text"));
    assert!(
        !model.text().contains("fetch"),
        "script body must never contribute reading text"
    );
}

#[test]
fn scripted_epub_fixture_declines_semantics_but_preserves_bytes() {
    // Parse the committed scripted chapter bytes through the content parser.
    let path = fixture_dir().join("epub_scripted.epub");
    let bytes = std::fs::read(path).expect("fixture");
    // The opaque floor is the invariant that always holds.
    let (descriptor, _) = vole_document::encode::encode(&bytes, Limits::DEFAULT).unwrap();
    let (out, _) =
        vole_document::materialize::decode_to_bytes(&descriptor, Limits::DEFAULT).unwrap();
    assert_eq!(out, bytes);
}
