def pragmas(config, durability):
    """The durability + performance PRAGMAs, stated explicitly per lane.

    `journal_mode=WAL` is used for every lane so the durability contract is
    comparable: WAL keeps the database *consistent* after a crash but, under
    `synchronous=NORMAL`, may lose the latest committed transactions on certain
    power failures. `synchronous=FULL` removes that exposure at a per-commit
    fsync cost; the court reports both (matched NORMAL for the headline).
    """
    sync = "FULL" if durability == "full" else "NORMAL"
    cache = {"minimal": -2000, "fts": -8000, "structural": -8000}.get(config, -65536)
    mmap = 0 if config == "minimal" else 268435456
    lines = [
        "PRAGMA journal_mode=WAL;",
        "PRAGMA synchronous=%s;" % sync,
        "PRAGMA cache_size=%d;" % cache,
        "PRAGMA temp_store=MEMORY;",
        "PRAGMA mmap_size=%d;" % mmap,
        "PRAGMA foreign_keys=OFF;",
    ]
    if config == "hybrid":
        # Strongest practical tuning: bigger cache + a large WAL journal budget so
        # the single build transaction does not force an in-transaction checkpoint.
        lines.append("PRAGMA cache_size=-131072;")
        lines.append("PRAGMA journal_size_limit=268435456;")
    return "\n".join(lines) + "\n"


def _base_tables():
    return """
CREATE TABLE documents(
  doc_id INTEGER PRIMARY KEY, format TEXT NOT NULL, path TEXT NOT NULL,
  source_len INTEGER NOT NULL, source_sha256 TEXT NOT NULL,
  pages INTEGER, spine INTEGER, doc_text TEXT);
CREATE TABLE blocks(
  block_id INTEGER PRIMARY KEY, doc_id INTEGER NOT NULL, unit TEXT NOT NULL,
  ordering INTEGER NOT NULL, kind TEXT NOT NULL, text TEXT NOT NULL,
  text_sha256 TEXT NOT NULL);
CREATE TABLE headings(
  heading_id INTEGER PRIMARY KEY, doc_id INTEGER NOT NULL, block_id INTEGER NOT NULL,
  level INTEGER NOT NULL, ord INTEGER NOT NULL);
CREATE TABLE db_tables(
  table_id INTEGER PRIMARY KEY, doc_id INTEGER NOT NULL, block_id INTEGER NOT NULL,
  n_rows INTEGER, n_cols INTEGER);
CREATE TABLE table_cells(
  table_id INTEGER NOT NULL, r INTEGER NOT NULL, c INTEGER NOT NULL, text TEXT,
  PRIMARY KEY(table_id, r, c));
CREATE TABLE resources(
  resource_id INTEGER PRIMARY KEY, doc_id INTEGER NOT NULL, path TEXT NOT NULL,
  kind TEXT, member_bytes INTEGER, member_sha256 TEXT);
CREATE TABLE metadata(
  doc_id INTEGER NOT NULL, key TEXT NOT NULL, value TEXT, PRIMARY KEY(doc_id, key));
CREATE TABLE source_blob(doc_id INTEGER PRIMARY KEY, payload BLOB NOT NULL);
"""


def schema(config, effective, tuned_index=True):
    """Schema for `config` built to contract depth `effective`.

    Escalates exactly like the historical control (coord at C1, provenance at C2,
    revision lineage at C4; C3 reuses the retained source blob) so a config's
    build bytes/wall are directly comparable depth by depth. `minimal`/`fts` are
    clamped to C0 by the caller (CAP), so they never grow.
    """
    s = _base_tables()
    if config in ("structural", "full", "hybrid") and effective >= NEED_COORD:
        s += "ALTER TABLE blocks ADD COLUMN native_coord TEXT;\n"
        if tuned_index:
            s += "CREATE INDEX idx_blocks_coord ON blocks(doc_id, native_coord);\n"
        s += "CREATE INDEX idx_blocks_doc ON blocks(doc_id, unit, ordering);\n"
    elif config in ("full", "hybrid") and tuned_index:
        # Full/hybrid keep the doc/unit/ordering index even at C0 (a value lookup
        # index the contract's `text`/`heading` observations use). `minimal` omits
        # it on purpose: that is what "minimal indexing" means and what we charge.
        s += "CREATE INDEX idx_blocks_doc ON blocks(doc_id, unit, ordering);\n"
    if config in ("full", "hybrid") and effective >= NEED_PROV:
        s += """
CREATE TABLE provenance(
  block_id INTEGER PRIMARY KEY, doc_id INTEGER NOT NULL, class TEXT NOT NULL,
  member TEXT, span_start INTEGER, span_end INTEGER, member_len INTEGER);
CREATE INDEX idx_prov_doc ON provenance(doc_id);
"""
    if config in ("full", "hybrid") and effective >= NEED_REV:
        s += """
CREATE TABLE revisions(
  doc_id INTEGER PRIMARY KEY, family_id TEXT, member_id TEXT, is_head INTEGER NOT NULL);
CREATE INDEX idx_rev_family ON revisions(family_id);
"""
    if config == "fts":
        # ONE correctly tuned FTS5 index. External content (no duplicated text),
        # detail=none (document-level only — the cheapest useful FTS), no column
        # size bookkeeping, unicode61 with diacritic folding. NO trigram: the
        # contract has no substring/phrase observation, so a second index of that
        # kind is pure overhead. This lane exists to QUANTIFY that overhead.
        s += ("CREATE VIRTUAL TABLE fts USING fts5(text, content='blocks', "
              "content_rowid='block_id', detail=none, columnsize=0, "
              "tokenize='unicode61 remove_diacritics 2');\n")
    return s


