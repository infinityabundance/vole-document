def build(config, fmt, source, db_path, through, durability="normal",
          family="", member="", is_head=1, extract_json=None, metrics_path=None):
    if config not in CAP:
        raise SystemExit("unknown config %r" % config)
    eff = min(through, CAP[config])
    if config == "adaptive":
        eff = 0  # adaptive starts minimal; `ensure` materializes on demand.

    t0 = _now_us()
    if extract_json:
        with open(extract_json) as f:
            doc = json.load(f)
        load_us = _now_us() - t0
        extract_us = 0
    else:
        doc = CTRL.extract(fmt, source)
        extract_us = _now_us() - t0
        load_us = 0

    _rm(db_path)
    con = sqlite3.connect(db_path)
    con.executescript(pragmas(config, durability))
    con.executescript(schema(config, eff))
    cur = con.cursor()

    m = doc["metadata"]
    cur.execute("INSERT INTO documents VALUES(1,?,?,?,?,?,?,?)",
                (fmt, source, m.get("source_len", 0), m.get("source_sha256", ""),
                 m.get("pages"), m.get("spine"), doc.get("doc_text")))
    cur.executemany("INSERT OR REPLACE INTO metadata VALUES(1,?,?)",
                    [(k, str(v)) for k, v in m.items()])

    blocks = doc["blocks"]
    use_coord = eff >= NEED_COORD
    rows = []
    for i, b in enumerate(blocks):
        if use_coord:
            rows.append((i + 1, 1, b["unit"], b["ordering"], b["kind"], b["text"],
                         CTRL.text_sha(b["text"]), b["native_coord"]))
        else:
            rows.append((i + 1, 1, b["unit"], b["ordering"], b["kind"], b["text"],
                         CTRL.text_sha(b["text"])))
    if use_coord:
        cur.executemany("INSERT INTO blocks VALUES(?,?,?,?,?,?,?,?)", rows)
    else:
        cur.executemany("INSERT INTO blocks VALUES(?,?,?,?,?,?,?)", rows)

    block_ids = {b["ordering"]: i + 1 for i, b in enumerate(blocks)}
    cur.executemany("INSERT INTO headings VALUES(?,1,?,?,?)",
                    [(i + 1, block_ids.get(h["block"], 0), h["level"], i)
                     for i, h in enumerate(doc["headings"])])
    cur.executemany("INSERT INTO db_tables VALUES(?,1,?,?,?)",
                    [(i + 1, block_ids.get(t["block"], 0), t["n_rows"], t["n_cols"])
                     for i, t in enumerate(doc["tables"])])
    cur.executemany("INSERT INTO table_cells VALUES(?,?,?,?)",
                    [(c["table"] + 1, c["r"], c["c"], c["text"]) for c in doc["cells"]])
    cur.executemany("INSERT INTO resources VALUES(?,1,?,?,?,?)",
                    [(i + 1, r["path"], r.get("kind"), r.get("member_bytes"),
                      r.get("member_sha256")) for i, r in enumerate(doc["resources"])])

    if config == "fts":
        cur.execute("INSERT INTO fts(rowid,text) SELECT block_id,text FROM blocks")

    if eff >= NEED_PROV and config in ("full", "hybrid"):
        prow = []
        for i, b in enumerate(blocks):
            sp = b.get("span")
            prow.append((i + 1, 1, b["prov_class"], b.get("prov_member"),
                         sp[0] if sp else None, sp[1] if sp else None, None))
        cur.executemany("INSERT INTO provenance VALUES(?,?,?,?,?,?,?)", prow)

    with open(source, "rb") as f:
        payload = f.read()
    cur.execute("INSERT INTO source_blob VALUES(1,?)", (payload,))

    if eff >= NEED_REV and config in ("full", "hybrid"):
        cur.execute("INSERT INTO revisions VALUES(1,?,?,?)",
                    (family or None, member or os.path.basename(source),
                     1 if is_head else 0))

    con.commit()
    t_db = _now_us()
    con.close()
    close_us = _now_us() - t_db

    db_bytes = _file_bytes(db_path, db_path + "-wal", db_path + "-shm")
    metrics = {
        "config": config, "durability": durability, "through": through,
        "effective": eff, "extract_us": extract_us, "load_us": load_us,
        "db_us": t_db - t0 - load_us - extract_us, "close_us": close_us,
        "db_bytes": db_bytes,
        "blocks": len(blocks), "headings": len(doc["headings"]),
        "tables": len(doc["tables"]), "cells": len(doc["cells"]),
        "resources": len(doc["resources"]),
    }
    if metrics_path:
        with open(metrics_path, "w") as f:
            json.dump(metrics, f, sort_keys=True)
    return metrics


