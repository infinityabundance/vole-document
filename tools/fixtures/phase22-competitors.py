    en = sub.add_parser("ensure")
    en.add_argument("--config", required=True)
    en.add_argument("--db", required=True)
    en.add_argument("--format", required=True)
    en.add_argument("--source", required=True)
    en.add_argument("--depth", type=int, required=True)
    en.add_argument("--family", default="")
    en.add_argument("--member", default="")
    en.add_argument("--is-head", type=int, default=1)
    en.add_argument("--metrics", default=None)

    m = sub.add_parser("materialize")
    m.add_argument("--db", required=True)
    m.add_argument("--out", required=True)

    sg = sub.add_parser("sqlgen")
    sg.add_argument("--out", required=True)
    sg.add_argument("--depths", default="0 1 2 3 4 5")

    ag = sub.add_parser("aggregate")
    ag.add_argument("raw")
    ag.add_argument("campaign")
    ag.add_argument("--reps", type=int, default=3)
    ag.add_argument("--boot", type=int, default=20000)
    ag.add_argument("--seed", type=int, default=220019)
    ag.add_argument("--tie", type=float, default=0.10)

    ns = ap.parse_args(argv)

    if ns.cmd == "extract":
        doc = CTRL.extract(ns.format, ns.source)
        with open(ns.out, "w") as f:
            json.dump(doc, f, sort_keys=True)
        print(json.dumps({"ok": True, "blocks": len(doc["blocks"])}))
        return 0

    if ns.cmd == "build":
        m = build(ns.config, ns.format, ns.source, ns.db, ns.through, ns.durability,
                  ns.family, ns.member, ns.is_head, ns.extract_json, ns.metrics)
        print(json.dumps(m, sort_keys=True))
        return 0

    if ns.cmd == "ensure":
        m = ensure(ns.config, ns.db, ns.format, ns.source, ns.depth,
                   ns.family, ns.member, ns.is_head, ns.metrics)
        print(json.dumps(m, sort_keys=True))
        return 0

    if ns.cmd == "materialize":
        con = sqlite3.connect(ns.db)
        row = con.execute("SELECT payload FROM source_blob WHERE doc_id=1").fetchone()
        con.close()
        if row is None:
            return 3
        with open(ns.out, "wb") as f:
            f.write(row[0])
        return 0

    if ns.cmd == "sqlgen":
        # Identical SQL to the historical control: the observation queries are a
        # property of the CONTRACT, not of the physical tuning, so every lane is
        # served by the frozen control's `sql_for`.
        depths = [int(x) for x in ns.depths.split()]
        for d in depths:
            dd = os.path.join(ns.out, "C%d" % d)
            os.makedirs(dd, exist_ok=True)
            for fmt in ("pdf", "docx", "epub"):
                for obs in CTRL.FMT_OBS[fmt]:
                    with open(os.path.join(dd, "%s.%s.sql" % (fmt, obs)), "w") as f:
                        f.write(CTRL.sql_for(d, fmt, obs))
        print(json.dumps({"depths": depths}))
        return 0

    if ns.cmd == "aggregate":
        return aggregate(ns.raw, ns.campaign, ns.reps, ns.boot, ns.seed, ns.tie)

    return 2


