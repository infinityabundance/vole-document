def read_tsv(path):
    if not os.path.exists(path):
        return []
    with open(path) as fh:
        hdr = fh.readline().rstrip("\n").split("\t")
        rows = []
        for line in fh:
            if not line.strip():
                continue
            vals = line.rstrip("\n").split("\t")
            if len(vals) != len(hdr):
                continue
            rows.append(dict(zip(hdr, vals)))
        return rows


def percentile(vals, p):
    v = sorted(float(x) for x in vals)
    if not v:
        return 0.0
    if len(v) == 1:
        return v[0]
    k = (len(v) - 1) * p
    f = math.floor(k)
    c = math.ceil(k)
    if f == c:
        return v[int(k)]
    return v[f] * (c - k) + v[c] * (k - f)


def geomean(vals):
    v = [float(x) for x in vals if float(x) > 0]
    if not v:
        return 0.0
    return math.exp(sum(math.log(x) for x in v) / len(v))


def median(vals):
    v = [float(x) for x in vals]
    return statistics.median(v) if v else 0.0


def _collect(rows):
    """lane -> depth -> id -> rep -> us (rc-0 only)."""
    out = {}
    for r in rows:
        if r.get("rc") != "0":
            continue
        out.setdefault(r["lane"], {}).setdefault(r["depth"], {}).setdefault(
            r["id"], {})[int(r["rep"])] = int(r["us"])
    return out


def _collect_cold(rows):
    out = {}
    for r in rows:
        lane, depth, idv = r["lane"], r["depth"], r["id"]
        rep = int(r["rep"])
        cell = out.setdefault(lane, {}).setdefault(depth, {}).setdefault(idv, {})
        cell[rep] = cell.get(rep, 0) + int(r["us"])
    return out


def _flat(series, lane, depth):
    out = {}
    for idv, repmap in series.get(lane, {}).get(depth, {}).items():
        for rep, us in repmap.items():
            out.setdefault(idv, {})[rep] = us
    return out


def _pair(numer, denom):
    out = {}
    for idv in sorted(set(numer) & set(denom)):
        ratios = []
        for rep in sorted(set(numer[idv]) & set(denom[idv])):
            n, d = numer[idv][rep], denom[idv][rep]
            if d > 0 and n > 0:
                ratios.append(n / d)
        if ratios:
            out[idv] = ratios
    return out


def _boot_ci(by_doc, B, seed):
    rng = random.Random(seed)
    docs = sorted(by_doc.keys())
    if not docs:
        return 0.0, 0.0
    draws = []
    for _ in range(B):
        sample = []
        for _ in range(len(docs)):
            sample.extend(by_doc[rng.choice(docs)])
        draws.append(statistics.median(sample) if sample else 0.0)
    draws.sort()
    lo = draws[max(0, int(0.025 * B) - 1)]
    hi = draws[min(B - 1, int(0.975 * B))]
    return lo, hi


def _dominates(a, b):
    """a dominates b on (build, bytes, cold, warm): <= in all, < in at least one."""
    keys = ("build_ms", "bytes", "cold_ms", "warm_ms")
    le = all(a[k] <= b[k] for k in keys)
    lt = any(a[k] < b[k] for k in keys)
    return le and lt


def aggregate(raw, campaign, reps, boot, seed, tie):
    build = read_tsv(os.path.join(raw, "build_samples.tsv"))
    cold = read_tsv(os.path.join(raw, "cold_samples.tsv"))
    warm = read_tsv(os.path.join(raw, "warm_samples.tsv"))
    exact = read_tsv(os.path.join(raw, "exact.tsv"))
    bytes_rows = read_tsv(os.path.join(raw, "bytes.tsv"))
    env = {}
    try:
        env = json.load(open(os.path.join(raw, "environment.json")))
    except (OSError, ValueError):
        pass

    build_s = _collect(build)
    warm_s = _collect(warm)
    cold_s = _collect_cold(cold)

    ids = sorted({r["id"] for r in build})
    lanes = sorted({r["lane"] for r in build})
    sq_lanes = [l for l in lanes if l not in ("vole", "extract")]
    sq_lanes = [l for l in ("minimal", "fts", "structural", "full", "adaptive",
                            "hybrid", "hist") if l in lanes]

    def dep_series(kind, lane):
        return {"build": build_s, "warm": warm_s, "cold": cold_s}[kind].get(lane, {})

    def depths_for(lane):
        ds = {r["depth"] for r in build if r["lane"] == lane and r["rc"] == "0"}
        return sorted(ds, key=lambda x: (x != "all", int(x) if x.isdigit() else 0))

    # ---- persistent bytes (deterministic; sum over docs) -------------------
    bmap = {}       # lane -> depth -> id -> bytes
    fmap = {}       # lane -> depth -> id -> files
    for r in bytes_rows:
        bmap.setdefault(r["lane"], {}).setdefault(r["depth"], {})[r["id"]] = int(r["bytes"])
        fmap.setdefault(r["lane"], {}).setdefault(r["depth"], {})[r["id"]] = int(r["files"])
    bytes_by = {lane: {dep: sum(d.values()) for dep, d in dd.items()}
                for lane, dd in bmap.items()}
    files_by = {lane: {dep: sum(d.values()) for dep, d in dd.items()}
                for lane, dd in fmap.items()}

    # ---- per (lane, depth) pooled medians ---------------------------------
    def pooled(kind, lane, dep):
        s = dep_series(kind, lane).get(dep, {})
        vals = [v for repmap in s.values() for v in repmap.values()]
        return median(vals), geomean(vals), (statistics.stdev(vals) if len(vals) > 1 else 0.0)

    L = []
    A = L.append
    A("# Phase 22.1 — SQLite competitive envelope (equal-contract court)")
    A("")
    A("The historical control (`tools/fixtures/phase18-contract-packed.py`, with "
      "`journal_mode=WAL`, `synchronous=NORMAL`, and TWO full FTS5 indexes) is "
      "retained as a HISTORICAL CONTROL lane (`hist`). The envelope adds six "
      "purpose-tuned configurations. Same 12-document subset, same contract "
      "depths C0–C5, same answer SQL (the frozen control's `sql_for`), same "
      "accounting (persistent bytes = **sum of regular-file sizes**; `du -sb` is "
      "never used). Wall times are integer microseconds; `N={}` repetitions, "
      "paired and interleaved.".format(reps))
    A("")
    A("- documents: **{}**".format(", ".join(ids)))
    A("- paired-ratio estimator: per (doc, rep) VOLE/lane ratio; median + "
      "geometric mean; fixed-seed cluster bootstrap 95% CI over documents "
      "(`{}` resamples, seed {}); ±{:.0f}% per-document tie band.".format(
          boot, seed, 100 * tie))
    A("- configurations: `minimal`, `fts`, `structural`, `full`, `adaptive`, "
      "`hybrid`; historical control `hist`. Capability ceilings: " +
      ", ".join("`{}`≤C{}".format(c, CAP[c]) for c in ALL_CONFIGS) + ".")
    A("")

    # ---- build decomposition ---------------------------------------------
    A("## Build decomposition (extraction vs SQLite write)")
    A("")
    A("Each lane's build is a SINGLE process that extracts and writes (comparable "
      "to VOLE's native build and to the historical control). The shared "
      "Python+Poppler extraction is additionally measured once per (doc, rep) and "
      "shown as the `extract` column; `db` is the lane's process wall minus that "
      "shared extraction (it still contains the interpreter start-up and the DB "
      "write). VOLE has no separate extract column: its build is native.")
    A("")
    A("| lane | depth | extract med ms | db med ms | total med ms | bytes | files |")
    A("|---|---:|---:|---:|---:|---:|---:|")
    ex_rows = [r for r in build if r["lane"] == "extract" and r["rc"] == "0"]
    ex_med = median([int(r["us"]) for r in ex_rows]) if ex_rows else 0
    for lane in ["vole"] + sq_lanes:
        for dep in depths_for(lane):
            s = dep_series("build", lane).get(dep, {})
            dbv = [v for repmap in s.values() for v in repmap.values()]
            if not dbv:
                continue
            if lane == "vole":
                extr = 0
                dbmed = median(dbv)
            else:
                extr = ex_med
                dbmed = max(0, median(dbv) - ex_med)
            b = bytes_by.get(lane, {}).get(dep)
            f = files_by.get(lane, {}).get(dep)
            A("| {} | {} | {:.0f} | {:.0f} | {:.0f} | {} | {} |".format(
                lane, ("C%s" % dep) if dep.isdigit() else dep, extr / 1000, dbmed / 1000,
                (extr + dbmed) / 1000, b if b is not None else "-", f if f is not None else "-"))
    A("")
    A("`extract med` is the shared, separately-measured extraction; each SQLite "
      "lane's build wall in `raw/build_samples.tsv` is a single extract+write "
      "process, so `db med` = wall − `extract med` (floor 0). `extract med` also "
      "carries one Python interpreter start-up; the SQLite lanes' walls carry "
      "another, which an integrated native loader would amortize — an "
      "implementation cost of the Python-orchestrated competitor, stated not "
      "hidden.")
    A("")

    # ---- coverage ---------------------------------------------------------
    A("## Capability coverage (the gate: no omitted competitor capability)")
    A("")
    A("| lane | " + " | ".join("C%d" % d for d in range(6)) + " |")
    A("|---|" + "---|" * 6)
    cov = {"vole": {d: True for d in range(6)}}
    for c in ALL_CONFIGS:
        cov[c] = {d: d <= CAP[c] for d in range(6)}
    if "hist" in lanes:
        cov["hist"] = {d: True for d in range(6)}
    for lane in ["vole"] + sq_lanes:
        A("| {} | ".format(lane) + " | ".join(
            "yes" if cov.get(lane, {}).get(d) else "NO" for d in range(6)) + " |")
    A("")
    A("`minimal`/`fts` cover only C0; `structural` covers C0–C1; `full`/`adaptive`/"
      "`hybrid`/`hist`/VOLE cover the full C0–C5 contract. A configuration is "
      "only compared at a depth it actually covers.")
    A("")

    # ---- frontier ---------------------------------------------------------
    frontier_rows = {}   # depth -> {lane: metrics}
    for dep in range(6):
        for lane in ["vole"] + sq_lanes:
            if not cov.get(lane, {}).get(dep):
                continue
            ds = str(dep)
            bdep = "all" if lane == "vole" else ds
            bv = [v for repmap in dep_series("build", lane).get(bdep, {}).values()
                  for v in repmap.values()]
            cv = [v for repmap in dep_series("cold", lane).get(ds, {}).values()
                  for v in repmap.values()]
            wv = [v for repmap in dep_series("warm", lane).get(ds, {}).values()
                  for v in repmap.values()]
            if not bv or not wv:
                continue
            byt = bytes_by.get(lane, {}).get(ds)
            frontier_rows.setdefault(dep, {})[lane] = {
                "build_ms": median(bv) / 1000,
                "bytes": byt if byt is not None else 0,
                "cold_ms": median(cv) / 1000,
                "warm_ms": median(wv) / 1000,
            }

    A("## Pareto frontier — build / persistent bytes / cold / warm")
    A("")
    A("Each cell is the pooled median over documents×reps (cold = sum of the "
      "per-observation process walls per rep; warm = the one-session batch). "
      "`*` marks Pareto-optimal points within a depth across (build, bytes, cold, "
      "warm); a point is dominated if another is ≤ in every axis and < in one.")
    A("")
    for dep in range(6):
        rows = frontier_rows.get(dep, {})
        if not rows:
            continue
        names = sorted(rows.keys(), key=lambda x: rows[x]["build_ms"])
        pareto = set()
        for a in names:
            if not any(_dominates(rows[b], rows[a]) for b in names if b != a):
                pareto.add(a)
        A("### C{}".format(dep))
        A("")
        A("| lane | build ms | bytes | cold ms | warm ms | pareto |")
        A("|---|---:|---:|---:|---:|:--:|")
        for a in names:
            r = rows[a]
            A("| {}{} | {:.1f} | {} | {:.2f} | {:.2f} | {} |".format(
                a, "", r["build_ms"], r["bytes"], r["cold_ms"], r["warm_ms"],
                "*" if a in pareto else ""))
        A("")
        vole = rows.get("vole")
        if vole:
            for a in names:
                if a == "vole":
                    continue
                r = rows[a]
                wins = []
                for k in ("build_ms", "bytes", "cold_ms", "warm_ms"):
                    if vole[k] < r[k]:
                        wins.append(k)
                    elif r[k] < vole[k]:
                        wins.append("-" + k)
                A("- VOLE vs `{}`: ".format(a) + ", ".join(wins) if wins else
                  "- VOLE vs `{}`: equal".format(a))
        A("")

    # ---- paired VOLE vs each lane, per depth ------------------------------
    A("## Paired VOLE/lane ratios (metric < 1 favours VOLE)")
    A("")
    A("| depth | lane | n docs | build med (CI) | cold med (CI) | warm med (CI) | bytes ratio |")
    A("|---|---|---:|---|---|---|---:|")
    for dep in range(6):
        for lane in sq_lanes:
            if not cov.get(lane, {}).get(dep):
                continue
            ds = str(dep)
            b = _pair(_flat(build_s, "vole", "all"), _flat(build_s, lane, ds))
            c = _pair(_flat(cold_s, "vole", ds), _flat(cold_s, lane, ds))
            w = _pair(_flat(warm_s, "vole", ds), _flat(warm_s, lane, ds))
            if not b and not w:
                continue
            bm = median([r for x in b.values() for r in x]) if b else 0.0
            blo, bhi = _boot_ci(b, boot, seed) if b else (0, 0)
            cm = median([r for x in c.values() for r in x]) if c else 0.0
            clo, chi = _boot_ci(c, boot, seed) if c else (0, 0)
            wm = median([r for x in w.values() for r in x]) if w else 0.0
            wlo, whi = _boot_ci(w, boot, seed) if w else (0, 0)
            vb = bytes_by.get("vole", {}).get(ds)
            lb = bytes_by.get(lane, {}).get(ds)
            br = (vb / lb) if (vb and lb) else 0.0
            A("| C{} | {} | {} | {:.3f} ({:.3f}..{:.3f}) | {:.3f} ({:.3f}..{:.3f}) | "
              "{:.3f} ({:.3f}..{:.3f}) | {:.3f} |".format(
                  dep, lane, len(b), bm, blo, bhi, cm, clo, chi, wm, wlo, whi, br))
    A("")

    # ---- durability FULL cost --------------------------------------------
    dur = read_tsv(os.path.join(raw, "durability.tsv"))
    if dur:
        A("## `synchronous=FULL` cost (measured, reported separately)")
        A("")
        A("Matched-setup builds are `synchronous=NORMAL`. This is the SAME build "
          "at `synchronous=FULL` (per-commit WAL `fsync`), for the `full` C5 "
          "configuration.")
        A("")
        A("| id | NORMAL db ms | FULL db ms | ratio | bytes NORMAL | bytes FULL |")
        A("|---|---:|---:|---:|---:|---:|")
        nb = {r["id"]: r for r in dur if r["durability"] == "normal"}
        fb = {r["id"]: r for r in dur if r["durability"] == "full"}
        for i in sorted(set(nb) & set(fb)):
            n0, f0 = int(nb[i]["db_us"]), int(fb[i]["db_us"])
            A("| {} | {:.1f} | {:.1f} | {:.2f} | {} | {} |".format(
                i, n0 / 1000, f0 / 1000, (f0 / n0 if n0 else 0),
                nb[i]["bytes"], fb[i]["bytes"]))
        A("")

    # ---- exactness --------------------------------------------------------
    A("## Exact original closure (length + SHA-256 + byte compare)")
    A("")
    A("| id | fmt | VOLE ok | control ok | competitors ok |")
    A("|---|---|:--:|:--:|:--:|")
    byid = {}
    fmt_by_id = {}
    for r in exact:
        byid.setdefault(r["id"], {})[r["lane"]] = r["ok"]
        fmt_by_id[r["id"]] = r["fmt"]
    for i in ids:
        m = byid.get(i, {})
        comp = [v for k, v in m.items() if k not in ("vole", "hist")]
        A("| {} | {} | {} | {} | {}/{} |".format(
            i, fmt_by_id.get(i, m.get("fmt", "")), m.get("vole", "?"), m.get("hist", "?"),
            sum(1 for v in comp if v == "1"), len(comp)))
    A("")

    # ---- answer equivalence ----------------------------------------------
    envdir = os.path.join(raw, "env")
    fmt_of = {r["id"]: r["fmt"] for r in bytes_rows}
    fmt_of.update({r["id"]: r["fmt"] for r in build})
    lanes_env = [l for l in (["vole"] + sq_lanes) if l in lanes]
    A("## Answer equivalence (frozen control + VOLE vs every configuration)")
    A("")
    A("On the final repetition every lane's envelope for each (depth, fmt, "
      "observation) is retained under `raw/env/`. Because every SQLite lane is "
      "served by the SAME frozen `sql_for`, a configuration that carries the "
      "same capability must emit a **byte-identical** envelope to the `full` "
      "reference at the same depth (the historical `hist` control is compared "
      "where it was run, C0/C5). VOLE is compared field-by-field with the "
      "reference's `_equiv` (raw / projected / shape / divergent / mismatch).")
    A("")
    A("| lane | depth | envelopes | identical to `full` | VOLE-equiv raw/proj | shape/decline | divergent | mismatch |")
    A("|---|---:|---:|---:|---:|---:|---:|---:|")
    tot_ident = 0
    tot_env = 0
    tot_mm = 0
    tot_div = 0
    for lane in sq_lanes:
        for dep in depths_for(lane):
            n = ident = 0
            vm_raw = vm_shape = vm_div = bad = 0
            for i in ids:
                f = fmt_of.get(i)
                if not f:
                    continue
                for obs in CTRL.FMT_OBS[f]:
                    ctrl_p = os.path.join(envdir, "C%s" % dep,
                                          "%s.%s.%s.full.json" % (i, f, obs))
                    lp = os.path.join(envdir, "C%s" % dep,
                                      "%s.%s.%s.%s.json" % (i, f, obs, lane))
                    if not (os.path.exists(ctrl_p) and os.path.exists(lp)):
                        continue
                    n += 1
                    tot_env += 1
                    if open(ctrl_p, "rb").read() == open(lp, "rb").read():
                        ident += 1
                        tot_ident += 1
                    vp = os.path.join(envdir, "C%s" % dep,
                                      "%s.%s.%s.vole.json" % (i, f, obs))
                    if not os.path.exists(vp):
                        continue
                    try:
                        # an empty file is a typed decline (rc 6 unsupported), not
                        # a value mismatch.
                        if os.path.getsize(vp) == 0:
                            v = {"obs": obs, "declined": True,
                                 "reason": "unsupported"}
                        else:
                            v = CTRL._normalize_vole_answer(
                                json.load(open(vp)), f, obs, int(dep))
                        s = json.load(open(lp))
                        res, _d = CTRL._equiv(int(dep), f, obs, v, s)
                    except (OSError, ValueError):
                        res = "mismatch"
                    if res in ("raw", "projected"):
                        vm_raw += 1
                    elif res in ("shape", "decline", "observable", "capability"):
                        vm_shape += 1
                    elif res == "divergent":
                        vm_div += 1
                        tot_div += 1
                    else:
                        bad += 1
                        tot_mm += 1
            A("| {} | C{} | {} | {}/{} | {} | {} | {} | {} |".format(
                lane, dep, n, ident, n, vm_raw, vm_shape, vm_div, bad))
    A("")
    A("Across all compared cells: **{}/{}** configuration envelopes are "
      "byte-identical to the `full` reference; **{}** VOLE/comparison "
      "mismatches; **{}** are reported as `divergent` (PDF page text is an "
      "independent heuristic projection — VOLE's own parser vs Poppler — and is "
      "never counted as a contract failure).".format(
          tot_ident, tot_env, tot_mm, tot_div))
    A("")

    # ---- durability -------------------------------------------------------
    A("## Durability contracts (compared explicitly, not assumed equal)")
    A("")
    A("**SQLite `journal_mode=WAL`, `synchronous=NORMAL`** (the matched setting "
      "for the headline, matching VOLE's unproven power-loss boundary): the WAL "
      "keeps the database *internally consistent* after a crash, but SQLite "
      "documents that under certain power failures the **latest committed "
      "transactions may be lost**. There is no torn page and no corruption; the "
      "committed prefix is recoverable. `synchronous=FULL` would `fsync` the WAL "
      "on every commit (removing that exposure) at a per-commit latency cost; "
      "the `--durability full` variant of this fixture measures that cost and is "
      "reported separately in `raw/durability_full.*`.")
    A("")
    A("**VOLE packed store (ADR-0053; Phase 20.1)** with `SyncPolicy::Batch` "
      "(the default): records are forced to stable storage once per segment "
      "(seal/flush), the field manifest is **flushed before it is published**, "
      "and recovery is a strict **prefix** — no partial node is ever fetchable "
      "and every node is re-hashed against its id. A crash can therefore lose "
      "records appended since the last flush, but a published manifest is always "
      "consistent. Phase 20.1's 1,300-case fault-injection court passed under "
      "both policies with **zero** bad-hash and **zero** prefix violations, but "
      "it injects process death (`SIGKILL`/`abort`), which leaves the OS page "
      "cache intact: **no `fsync` boundary is actually exercised**, so true "
      "power loss and torn/lost rename remain **argued, not measured**.")
    A("")
    A("**Net.** Both sides at the matched setting can lose the tail of the most "
      "recent writes after a power failure; both preserve consistency and never "
      "expose a partial record. Neither side has a measured true-power-loss "
      "receipt. SQLite `synchronous=FULL` is the stronger, slower option; VOLE's "
      "`--sync=each` (per-record `fdatasync`) is its analogue and was also not "
      "measured under true power loss.")
    A("")

    # ---- answers ----------------------------------------------------------
    A("## Answers")
    A("")
    for dep in range(6):
        rows = frontier_rows.get(dep, {})
        if not rows or "vole" not in rows:
            continue
        v = rows["vole"]
        stronger = []
        for a, r in rows.items():
            if a == "vole":
                continue
            if r["build_ms"] <= v["build_ms"]:
                stronger.append((a, "build"))
            if r["bytes"] and r["bytes"] <= v["bytes"]:
                stronger.append((a, "bytes"))
            if r["warm_ms"] <= v["warm_ms"]:
                stronger.append((a, "warm"))
        if stronger:
            A("- **C{}**: configurations at least matching VOLE — ".format(dep) +
              "; ".join("`{}`≤VOLE on {}".format(a, k) for a, k in stronger) + ".")
        else:
            A("- **C{}**: VOLE is best-or-equal on every axis vs the covering "
              "configurations.".format(dep))
    A("")

    A("## Caveats and honesty")
    A("")
    A("- The store is the bind-mounted `/work`; per-cell CV is in "
      "`raw/per_doc_lane_depth.csv`. Wide intervals are reported wide.")
    A("- `full`/`hybrid` exclude FTS because the contract has **no search "
      "observation**; `hist` carries the control's two FTS indexes and `fts` "
      "carries one tuned index, so the FTS overhead is quantified, not hidden.")
    A("- `hybrid`'s 'native parser/cache' is Poppler (PDF) + Python stdlib "
      "(OOXML/EPUB) — the strongest native extraction available in the pinned "
      "image without modifying `src/`; it is NOT a rewrite of VOLE's adapters.")
    A("- Cells are pooled medians; the paired per-rep CI is the estimator for "
      "ratio claims (ADR-0054). `hist` is measured only at C0 and C5 as a "
      "control point, not at every depth.")
    A("- `adaptive`'s cold column is large at deeper depths **by construction**: "
      "its lazy materialization is charged to the first cold call at each depth "
      "(`raw/cold_samples.tsv` `obs=ensure`), whereas `full`/`hybrid`/`hist` "
      "paid that cost at build. Its warm session and its bytes are the honest "
      "after-materialization numbers.")
    A("")

    report = "\n".join(L)
    with open(os.path.join(campaign, "SUMMARY.md"), "w") as f:
        f.write(report)

    # ---- FRONTIER.md ------------------------------------------------------
    F = []
    F.append("# Phase 22.1 — Pareto frontier (VOLE vs the SQLite envelope)")
    F.append("")
    F.append("Per depth, the covering configurations' pooled medians. `bytes` is "
             "the sum over the 12 documents of regular-file bytes.")
    F.append("")
    for dep in range(6):
        rows = frontier_rows.get(dep, {})
        if not rows:
            continue
        names = sorted(rows.keys(), key=lambda x: rows[x]["build_ms"])
        pareto = set(a for a in names
                     if not any(_dominates(rows[b], rows[a]) for b in names if b != a))
        F.append("## C{}".format(dep))
        F.append("")
        F.append("| lane | build ms | bytes | cold ms | warm ms | Pareto |")
        F.append("|---|---:|---:|---:|---:|:--:|")
        for a in names:
            r = rows[a]
            F.append("| {} | {:.1f} | {} | {:.2f} | {:.2f} | {} |".format(
                a, r["build_ms"], r["bytes"], r["cold_ms"], r["warm_ms"],
                "yes" if a in pareto else ""))
        F.append("")
    frontier = "\n".join(F)
    with open(os.path.join(campaign, "FRONTIER.md"), "w") as f:
        f.write(frontier)

    # per-doc CSV
    with open(os.path.join(raw, "per_doc_lane_depth.csv"), "w") as fh:
        fh.write("kind,id,lane,depth,n,median_ms,mean_ms,min_ms,max_ms,cv\n")
        for kind in ("build", "warm", "cold"):
            series = {"build": build_s, "warm": warm_s, "cold": cold_s}[kind]
            for lane in ["vole"] + sq_lanes:
                for dep, byid in series.get(lane, {}).items():
                    for idv in ids:
                        repmap = byid.get(idv)
                        if not repmap:
                            continue
                        v = [x / 1000.0 for x in repmap.values()]
                        mean = statistics.fmean(v)
                        sd = statistics.stdev(v) if len(v) > 1 else 0.0
                        fh.write("{},{},{},{},{},{:.3f},{:.3f},{:.3f},{:.3f},{:.4f}\n".format(
                            kind, idv, lane, dep, len(v), statistics.median(v), mean,
                            min(v), max(v), sd / mean if mean else 0.0))

    print(report)
    return 0


