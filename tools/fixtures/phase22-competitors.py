# Capability ceiling: the deepest contract depth each configuration covers.
CAP = {
    "minimal": 0,
    "fts": 0,
    "structural": 1,
    "full": 5,
    "adaptive": 5,
    "hybrid": 5,
}

# Required structural depth for each optional projection.
NEED_COORD = 1
NEED_PROV = 2
NEED_EXACT = 3
NEED_REV = 4

ALL_CONFIGS = ["minimal", "fts", "structural", "full", "adaptive", "hybrid"]


def _rm(p):
    for suf in ("", "-wal", "-shm", "-journal"):
        try:
            os.remove(p + suf)
        except FileNotFoundError:
            pass


def _now_us():
    return int(time.monotonic() * 1_000_000)


def _file_bytes(*paths):
    """SUM OF REGULAR-FILE SIZES (ADR-0049). Never `du -sb`."""
    total = 0
    for p in paths:
        try:
            total += os.path.getsize(p)
        except OSError:
            pass
    return total


