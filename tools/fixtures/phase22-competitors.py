#!/usr/bin/env python3
# Phase 22.1 — the SQLite competitive envelope.
#
# ## Why this file exists
#
# The Phase-16/18/19 equal-contract court measured VOLE against ONE SQLite
# baseline (`tools/fixtures/phase18-contract-packed.py`), which is retained here
# UNMODIFIED as the historical control. That baseline is defensible but is not
# necessarily SQLite's cheapest honest configuration for the workload:
#
#   * it runs `journal_mode=WAL`, `synchronous=NORMAL` (never compared to VOLE's
#     own durability boundary);
#   * it carries TWO full FTS5 indexes (`fts` unicode61 + `fts_tri` trigram) that
#     the C0..C5 contract NEVER exercises (there is no search observation);
#   * its build wall mixes Python orchestration + Poppler extraction with the
#     SQLite write, and it writes rows one `execute()` at a time, no `executemany`,
#     no explicit cache budget;
#   * its storage headline is a point estimate against that one baseline.
#
# So its ~0.96x (median) build ratio and ~0.9x byte ratio are legitimate AGAINST
# THAT BASELINE but are not evidence against the Pareto-optimal SQLite an expert
# would build. This file builds that envelope.
#
# ## The envelope (one lane per configuration; nothing is substituted)
#
#   minimal    source + value/metadata tables, minimal indexing.       cap C0
#   fts        minimal + ONE correctly tuned FTS5 index, external        cap C0
#              content, detail=none, columnsize=0, unicode61 — no
#              trigram (the contract never asks for substring search,
#              so an FTS index is pure overhead here; we quantify it).
#   structural minimal + native coordinates (column + index).           cap C1
#   full       all required contract projections (value, coord,          cap C5
#              provenance, exact closure, revision lineage), NO FTS —
#              i.e. the Phase-16/18 contract without its dead indexes.
#   adaptive   builds minimal and materializes a structure the first     cap C5
#              time a contract depth demands it; ALL cost charged.
#   hybrid     `full` + strongest physical tuning + the native          cap C5
#              (Poppler) extractor path for PDF; see the limitation
#              noted in `build()`.
#
# Every configuration gets: WAL, an explicit `synchronous` (NORMAL or FULL),
# `cache_size`, `temp_store`, `mmap_size`, one transaction per build, and
# `executemany` batching. Durability is a flag so the court can run a MATCHED
# setting for the headline and report the other separately.
#
# ## What this file does NOT do
#
# It does not touch `phase18-contract-packed.py`, any phase-1{6,7,8,9}/
# phase-19/phase-20 court, `real100-v1/`, or `src/`. It creates new files only.
# It writes no wire byte and changes no decode path; exactness stays
# `materialize(descriptor) == original_bytes`.
#
# ## Subcommands
#
#   extract  --format F --source S --out FILE
#   build    --config C --format F --source S --db D --through N [--durability S]
#            [--family ID] [--member ID] [--is-head 0|1] [--extract-json FILE]
#            [--metrics FILE]
#   ensure   --config C --db D --format F --source S --depth N [--family ID]
#            [--member ID] [--is-head 0|1] [--metrics FILE]   (adaptive only)
#   materialize --db D --out FILE
#   sqlgen   --out DIR --depths "0 1 2 3 4 5"     (identical SQL to the control)
#   aggregate RAW CAMPAIGN --reps N ...
#
# The observation SQL is generated by the UNCHANGED historical control
# (`phase18-contract-packed.py::sql_for`), so every competitor's answers are
# byte-comparable with the Phase-18 lane and with VOLE.

