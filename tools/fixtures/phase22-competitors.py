def _columns(con, table):
    return {r[1] for r in con.execute("PRAGMA table_info(%s)" % table)}


def ensure(config, db_path, fmt, source, depth, family="", member="", is_head=1,
           metrics_path=None):
    """Materialize, on first demand, whatever contract depth `depth` requires.

    Only `adaptive` uses this; other configs are already built for their depth.
    The re-extraction and the DDL/DML are timed together and charged here — this
    is the whole point of the lane (its "learning" is not free).
    """
    if config != "adaptive":
        return {"config": config, "ensure_us": 0, "materialized": []}
    t0 = _now_us()
    con = sqlite3.connect(db_path)
    con.executescript(pragmas(config, "normal"))
    cur = con.cursor()
    matd = []
    need_coord = depth >= NEED_COORD and "native_coord" not in _columns(con, "blocks")
    need_prov = depth >= NEED_PROV and not cur.execute(
        "SELECT 1 FROM sqlite_master WHERE type='table' AND name='provenance'").fetchone()
    need_rev = depth >= NEED_REV and not cur.execute(
        "SELECT 1 FROM sqlite_master WHERE type='table' AND name='revisions'").fetchone()
    need_index = (depth >= NEED_COORD and not cur.execute(
        "SELECT 1 FROM sqlite_master WHERE type='index' AND name='idx_blocks_doc'").fetchone())
    if not (need_coord or need_prov or need_rev or need_index):
        con.close()
        return {"config": config, "ensure_us": _now_us() - t0, "materialized": []}

    doc = CTRL.extract(fmt, source)
    if need_coord:
        cur.execute("ALTER TABLE blocks ADD COLUMN native_coord TEXT")
        cur.executemany("UPDATE blocks SET native_coord=? WHERE ordering=?",
                        [(b["native_coord"], b["ordering"]) for b in doc["blocks"]])
        cur.execute("CREATE INDEX idx_blocks_coord ON blocks(doc_id, native_coord)")
        matd.append("coord")
    if need_index:
        cur.execute("CREATE INDEX idx_blocks_doc ON blocks(doc_id, unit, ordering)")
        matd.append("idx_blocks_doc")
    if need_prov:
        cur.execute("""
CREATE TABLE provenance(
  block_id INTEGER PRIMARY KEY, doc_id INTEGER NOT NULL, class TEXT NOT NULL,
  member TEXT, span_start INTEGER, span_end INTEGER, member_len INTEGER)""")
        cur.execute("CREATE INDEX idx_prov_doc ON provenance(doc_id)")
        prow = []
        for i, b in enumerate(doc["blocks"]):
            sp = b.get("span")
            prow.append((i + 1, 1, b["prov_class"], b.get("prov_member"),
                         sp[0] if sp else None, sp[1] if sp else None, None))
        cur.executemany("INSERT INTO provenance VALUES(?,?,?,?,?,?,?)", prow)
        matd.append("provenance")
    if need_rev:
        cur.execute("""
CREATE TABLE revisions(
  doc_id INTEGER PRIMARY KEY, family_id TEXT, member_id TEXT, is_head INTEGER NOT NULL)""")
        cur.execute("CREATE INDEX idx_rev_family ON revisions(family_id)")
        cur.execute("INSERT INTO revisions VALUES(1,?,?,?)",
                    (family or None, member or os.path.basename(source),
                     1 if is_head else 0))
        matd.append("revisions")
    con.commit()
    con.close()
    metrics = {"config": config, "depth": depth, "ensure_us": _now_us() - t0,
               "materialized": matd}
    if metrics_path:
        with open(metrics_path, "w") as f:
            json.dump(metrics, f, sort_keys=True)
    return metrics


